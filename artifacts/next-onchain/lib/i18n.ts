// Central translation dictionary for the whole app. Locale is detected once
// server-side from the Accept-Language header (see app/layout.tsx) so the
// very first render already has the right language — no flash of English
// before a client-side useEffect corrects it.

export const LOCALES = ["en", "tr", "de", "zh", "es", "fr", "pt"] as const;
export type Locale = (typeof LOCALES)[number];

export function detectLocale(acceptLanguage?: string | null): Locale {
  if (!acceptLanguage) return "en";
  const candidates = acceptLanguage
    .split(",")
    .map((part) => part.trim().split(";")[0].split("-")[0].toLowerCase());
  for (const candidate of candidates) {
    if ((LOCALES as readonly string[]).includes(candidate)) {
      return candidate as Locale;
    }
  }
  return "en";
}

